from pathlib import Path

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=str(Path(__file__).resolve().parents[2] / ".env"),
        env_file_encoding="utf-8",
        extra="ignore",
    )

    DATABASE_URL: str
    SECRET_KEY: str
    ALGORITHM: str = "HS256"
    ACCESS_TOKEN_EXPIRE_MINUTES: int = 480
    ENVIRONMENT: str = "development"
    # "cloud" (default): DATABASE_URL is the live database — current behaviour.
    # "local": the app runs against LOCAL_DATABASE_URL (SQLite on this machine)
    # and syncs to DATABASE_URL (the cloud Postgres) whenever it is reachable.
    POS_MODE: str = "cloud"
    LOCAL_DATABASE_URL: str = "sqlite:///./data/mjpos_local.db"
    SYNC_INTERVAL_SECONDS: int = 30
    # Locally-generated primary keys start above this offset so they can never
    # collide with rows created on the cloud database by other terminals.
    LOCAL_ID_OFFSET: int = 1_500_000_000
    # Every offline terminal owns one block of ids: [offset, offset + BLOCK).
    # Block 0 starts at LOCAL_ID_BASE; installed tills claim the next free
    # block from the cloud ``pos_till_blocks`` registry (app.till_setup).
    # Ids below the base were generated by the cloud database itself.
    LOCAL_ID_BASE: int = 1_500_000_000
    LOCAL_ID_BLOCK: int = 10_000_000
    MAX_FAILED_LOGINS: int = 5
    LOCKOUT_MINUTES: int = 15
    # Sales tax / VAT. Ghana standard combined levy is 0.219 (VAT 15% + NHIL 2.5%
    # + GETFund 2.5% + COVID 1%). Left at 0 by default so existing totals are
    # unchanged until the business explicitly enables it.
    TAX_RATE: float = 0.0
    # True  = shelf prices already include tax (tax is backed out of the total)
    # False = tax is added on top of the net total
    TAX_INCLUSIVE: bool = True
    COMPANY_NAME: str = "MJ Electricals Ghana Limited"
    COMPANY_TIN: str = ""
    CORS_ORIGINS: list[str] = [
        "http://localhost:3000",
        "http://127.0.0.1:3000",
    ]
    # Website backend admin API — proxied server-side so the admin key and
    # website-management permissions are never exposed to the browser.
    WEBSITE_API_URL: str = "http://127.0.0.1:8001"
    WEBSITE_ADMIN_KEY: str = ""


settings = Settings()
